package com.calorietracker.app.data.model

data class UserProfile(
  val name: String = "",
  val age: Int = 30,
  val gender: String = "Male",
  val heightCm: Float = 170f,
  val weightKg: Float = 70f,
  val targetWeightKg: Float = 65f,
  val gymDaysPerWeek: Int = 3,
  val activityLevel: String = "MODERATE", // see ActivityLevel
  val goalType: String = "LOSE", // LOSE, MAINTAIN, GAIN
  val weeklyRateKg: Float = 0.5f,
  val cuisine: String = "Indian",
  val dietType: String = "No restriction",
  /** False until the user has saved the profile form once; drives the setup prompts. */
  val profileConfigured: Boolean = false,
  val primaryAiProvider: String = "Gemini", // Gemini, OpenAI, Claude, DeepSeek
  val geminiApiKey: String = "",
  val openAiApiKey: String = "",
  val claudeApiKey: String = "",
  val deepSeekApiKey: String = "",
  val geminiModel: String = "gemini-3.6-flash",
  val openAiModel: String = "gpt-4o-mini",
  val claudeModel: String = "claude-3-5-sonnet-20240620",
  val deepSeekModel: String = "deepseek-chat",
  val notificationsEnabled: Boolean = true,

  // Goals, generated by GoalPlanner from the fields above (or set manually)
  val bmrCalories: Int = 1600,
  val tdeeMaintenanceCalories: Int = 2400,
  val targetDailyCalories: Int = 2000,
  val targetDailyProteinGrams: Float = 110f,
  val targetDailyCreatineGrams: Float = 5f,
  val targetWaterLiters: Float = 2.5f
) {
  /** Name for greetings and prompts when the user hasn't entered one yet. */
  val displayName: String
    get() = name.trim().ifBlank { "there" }
}
